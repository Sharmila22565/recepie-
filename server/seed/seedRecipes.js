const seedDatabase = async () => {
  try {
    const recipeCount = await Recipe.countDocuments();
    if (recipeCount > 0) {
      console.log(`Database already has ${recipeCount} recipes. Skipping seed.`);
      return;
    }

    console.log('Seeding initial recipes and mock chef user...');

    // Find or create Chef RecipeShare user
    let chefUser = await User.findOne({ email: 'chef@recipeshare.com' });
    if (!chefUser) {
      chefUser = await User.create({
        name: 'Executive Chef Sharma',
        email: 'chef@recipeshare.com',
        password: 'Password123!',
        bio: 'Culinary artist & master chef with 15+ years of culinary experience across traditional Indian and global cuisines.',
        profileImage: 'https://images.unsplash.com/photo-1577219491135-ce391730fb2c?auto=format&fit=crop&w=400&q=80',
      });
    }

    // Attach author ID to recipes
    const recipesToInsert = sampleRecipes.map((r) => ({
      ...r,
      author: chefUser._id,
      authorName: chefUser.name,
    }));

    const insertedRecipes = await Recipe.insertMany(recipesToInsert);
    console.log(` Successfully seeded ${insertedRecipes.length} authentic recipes into MongoDB!`);

    // Add some realistic sample reviews
    if (insertedRecipes.length > 0) {
      const sampleReviewers = [
        { name: 'Priya Sundaram', comment: 'Made this for Sunday family brunch and everyone fell in love! So authentic and easy to follow.', rating: 5 },
        { name: 'Aarav Mehta', comment: 'The step-by-step instructions made this foolproof. Turned out restaurant quality on my first try!', rating: 5 },
        { name: 'Neha Kapoor', comment: 'The spice balance and tips were spot on. Bookmarking this as my go-to recipe!', rating: 5 },
      ];

      for (let i = 0; i < Math.min(6, insertedRecipes.length); i++) {
        const rev = sampleReviewers[i % sampleReviewers.length];
        await Review.create({
          userId: chefUser._id,
          userName: rev.name,
          userAvatar: `https://images.unsplash.com/photo-${1534528741775 + i}?auto=format&fit=crop&w=150&q=80`,
          recipeId: insertedRecipes[i]._id,
          rating: rev.rating,
          comment: rev.comment,
        });
      }
      console.log(' Successfully seeded sample reviews and ratings.');
    }
  } catch (error) {
    console.error('Error during database seed:', error);
  }
};

module.exports = { seedDatabase, sampleRecipes };

if (require.main === module) {
  const { connectDB, disconnectDB } = require('../config/db');
  require('dotenv').config();

  (async () => {
    await connectDB();
    await Recipe.deleteMany({});
    await Review.deleteMany({});
    await Favorite.deleteMany({});
    await seedDatabase();
    console.log('Seed completed. Exiting...');
    await disconnectDB();
    process.exit(0);
  })();
}
